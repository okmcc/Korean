// Watch: real Korean clips from YouTube with study controls.
import { h, setMain, playBtn, toast, today } from '../ui.js';
import * as D from '../data.js';
import { S, save } from '../store.js';
import { grade } from '../srs.js';
import { nextLesson } from '../progress.js';

const LEVELS = [[1, 5, 'Beginner · Units 1–5'], [6, 14, 'Phase 1 · Units 6–14'], [15, 27, 'Phase 2 · Units 15–27'], [28, 40, 'Phase 2 · Units 28–40']];
let ytReady = null;
function loadYT() {
  if (ytReady) return ytReady;
  ytReady = new Promise((res, rej) => {
    if (window.YT?.Player) return res(window.YT);
    window.onYouTubeIframeAPIReady = () => res(window.YT);
    const s = document.createElement('script'); s.src = 'https://www.youtube.com/iframe_api'; s.onerror = () => rej(new Error('YouTube could not load'));
    document.head.append(s);
  });
  return ytReady;
}

export default async function (id) {
  const clips = await D.clips();
  if (id) return player(clips.find(c => c.id === id));
  const st = S();
  const L = await nextLesson();
  const lvl = L ? L.unit : 40;
  const m = setMain(h('h1', {}, 'Watch'),
    h('p', { class: 'muted' }, 'Real Korean from YouTube: learner videos first, then scenes from popular dramas and movies. Each clip has slow-down, replay and loop buttons, plus Korean captions when the video has them.'),
    h('p', { class: 'small muted' }, `Clips up to Unit ${lvl} are best for you right now. Harder ones are fine too — just aim to catch a few words.`));
  for (const [a, b, label] of LEVELS) {
    const list = clips.filter(c => c.level >= a && c.level <= b);
    if (!list.length) continue;
    m.append(h('div', { class: 'section-title' }, label), h('div', { class: 'stack' }, list.map(c => h('a', { class: 'clip', href: `#/watch/${c.id}` },
      h('img', { src: `https://i.ytimg.com/vi/${c.yt}/mqdefault.jpg`, alt: '', loading: 'lazy', onerror: (e) => { e.currentTarget.style.visibility = 'hidden'; } }),
      h('div', { class: 'grow' }, h('b', {}, c.title), h('span', { class: 'muted small' }, `${c.show} · ${c.kind} · ${mins(c.len)}`),
        c.level > lvl ? h('span', { class: 'pill', style: { marginLeft: '6px' } }, `after Unit ${c.level}`) : null,
        st.clips[c.id] ? h('span', { class: 'pill good', style: { marginLeft: '6px' } }, 'watched') : null)))));
  }
  m.append(h('p', { class: 'small muted', style: { marginTop: '18px' } }, 'Want more? ',
    h('a', { href: searchUrl('Korean drama clip with Korean subtitles'), target: '_blank', rel: 'noopener' }, 'Search YouTube for Korean clips'),
    '. Clips play from YouTube and belong to their owners.'));
}

const mins = (s) => !s ? '' : s < 60 ? `${s} sec` : s < 5400 ? `${Math.round(s / 60)} min` : `${Math.round(s / 3600)} hr`;
const searchUrl = (q) => `https://www.youtube.com/results?search_query=${encodeURIComponent(q)}`;
const CC = { 'ko': 'Korean captions made by the creator. Turn them on with the Captions button.', 'ko-auto': 'Korean captions are auto-generated by YouTube, so they can have mistakes.', 'en-burned': 'English subtitles are built into the video.', '': 'No Korean captions on this one. Just listen.' };

async function player(c) {
  if (!c) { setMain(h('p', {}, 'Clip not found.'), h('a', { class: 'btn', href: '#/watch' }, 'All clips')); return; }
  const st = S();
  const holder = h('div', { id: 'ytp' });
  const wrap = h('div', { class: 'video-wrap' }, holder);
  const bar = h('div', { class: 'player-bar' });
  const msg = h('div');
  const ytLink = `https://www.youtube.com/watch?v=${c.yt}${c.start ? `&t=${c.start}s` : ''}`;
  let readCard = null;
  if (c.ko) {
    const mean = h('p', { class: 'muted', hidden: true }, c.koEn);
    readCard = h('div', { class: 'card', style: { marginTop: '14px' } }, h('h3', {}, 'Read it in Korean'),
      h('div', { class: 'read-line' }, playBtn(c.ko), h('b', { lang: 'ko' }, c.ko)),
      mean,
      h('button', { class: 'btn btn-ghost', onclick: (e) => { mean.hidden = false; e.currentTarget.remove(); } }, 'Show meaning'),
      c.koNote ? h('p', { class: 'small muted' }, c.koNote + '.') : null,
      st.mylines.some(x => x.clip === c.id && x.ko === c.ko) ? h('p', { class: 'small' }, '✓ In your reviews') :
        h('button', { class: 'btn', onclick: (e) => {
          const mid = Date.now().toString(36);
          st.mylines.push({ id: mid, ko: c.ko, en: c.koEn, clip: c.id });
          st.cards['M:' + mid] = grade({ k: 'M:' + mid, u: 0, l: '' }, 3, today());
          save(true); e.currentTarget.replaceWith(h('p', { class: 'small' }, '✓ In your reviews')); toast('Added to your reviews');
        } }, 'Add this line to my reviews'),
      (c.kw || []).length ? [h('p', { class: 'small', style: { marginTop: '10px' } }, 'Words from the course:'),
        h('div', {}, c.kw.map(([w, g, u]) => h('div', { class: 'kw' }, playBtn(w, { small: true }), h('div', {}, h('b', { lang: 'ko' }, w), ' ', h('span', { class: 'g' }, g)), h('span', { class: 'pill' }, `Unit ${u}`))))] : null);
  }
  const m = setMain(h('a', { class: 'btn btn-ghost', href: '#/watch' }, '← All clips'),
    h('h1', {}, c.title), h('p', { class: 'muted' }, `${c.show} · ${c.channel} · ${mins(c.len)}`),
    c.about ? h('p', {}, c.about) : null,
    wrap, bar, msg,
    h('p', { class: 'small muted', style: { marginTop: '8px' } }, CC[c.cc || ''] || ''),
    h('p', { class: 'small muted' }, 'Trouble playing? ', h('a', { href: ytLink, target: '_blank', rel: 'noopener' }, 'Open it on YouTube'),
      c.q ? [' · ', h('a', { href: searchUrl(c.q), target: '_blank', rel: 'noopener' }, 'Find more like this')] : null, '.'),
    c.tip ? h('div', { class: 'note', style: { marginTop: '14px' } }, h('h3', {}, 'Tip'), h('p', {}, c.tip)) : null,
    readCard);
  let yt;
  try { yt = await loadYT(); } catch (e) { msg.append(h('div', { class: 'feedback no' }, 'YouTube didn\'t load. Check your connection, or open the clip on YouTube.')); afterWatching(m, c, st); return; }
  const hasKo = (c.cc || '').startsWith('ko');
  let p, A = null, B = null, loopT = null, cc = hasKo;
  p = new yt.Player('ytp', {
    videoId: c.yt, host: 'https://www.youtube-nocookie.com',
    playerVars: { playsinline: 1, rel: 0, cc_load_policy: hasKo ? 1 : 0, cc_lang_pref: 'ko', hl: 'ko', start: c.start || 0, end: c.end || undefined, modestbranding: 1 },
    events: {
      onError: (e) => { msg.innerHTML = ''; msg.append(h('div', { class: 'feedback no' }, [101, 150, 153].includes(e.data) ? 'The owner doesn\'t allow this video to play inside other sites. Use the YouTube link below.' : 'This video can\'t play right now. Try the YouTube link below.')); },
    },
  });
  const btn = (label, fn, pressed) => { const b = h('button', { onclick: () => fn(b) }, label); if (pressed != null) b.setAttribute('aria-pressed', String(pressed)); return b; };
  bar.append(
    btn('▶ / ❚❚', () => { const s = p.getPlayerState?.(); if (s === 1) p.pauseVideo(); else p.playVideo(); }),
    btn('⟲ 5 sec', () => { p.seekTo(Math.max(0, p.getCurrentTime() - 5), true); p.playVideo(); }),
    btn('Speed 1×', (b) => { const r = p.getPlaybackRate(); const n = r === 1 ? 0.75 : r === 0.75 ? 0.5 : 1; p.setPlaybackRate(n); b.textContent = `Speed ${n}×`; }),
    btn('Loop: set A', (b) => {
      if (A == null) { A = p.getCurrentTime(); b.textContent = 'Loop: set B'; }
      else if (B == null) { B = p.getCurrentTime(); if (B <= A) { A = B = null; b.textContent = 'Loop: set A'; return; } b.textContent = 'Stop loop'; b.setAttribute('aria-pressed', 'true');
        loopT = setInterval(() => { if (p.getCurrentTime() >= B) p.seekTo(A, true); }, 200); p.seekTo(A, true); p.playVideo(); }
      else { clearInterval(loopT); A = B = null; b.textContent = 'Loop: set A'; b.setAttribute('aria-pressed', 'false'); }
    }),
    hasKo ? btn('Captions', (b) => { cc = !cc; try { if (cc) { p.loadModule('captions'); p.setOption('captions', 'track', { languageCode: 'ko' }); } else p.unloadModule('captions'); } catch (e) {} b.setAttribute('aria-pressed', String(cc)); }, true) : null);
  window.addEventListener('hashchange', () => clearInterval(loopT), { once: true });

  afterWatching(m, c, st);
}

function afterWatching(m, c, st) {
  const ta = h('input', { type: 'text', id: 'ml', placeholder: 'Korean you heard (optional)' });
  const note = h('input', { type: 'text', id: 'mn', placeholder: 'What it means (optional)' });
  m.append(h('div', { class: 'section-title' }, 'After watching'),
    h('div', { class: 'card' }, h('p', {}, 'How much did you understand?'),
      h('div', { class: 'seg' }, ['A few words', 'Some of it', 'Most of it'].map((t, i) => h('button', { onclick: (e) => {
        st.clips[c.id] = { d: today(), u: i }; save(); e.currentTarget.parentElement.querySelectorAll('button').forEach(b => b.setAttribute('aria-pressed', 'false')); e.currentTarget.setAttribute('aria-pressed', 'true'); toast('Saved. Rewatching later is great practice.');
      } }, t))),
      h('div', { class: 'spacer' }),
      h('p', {}, 'Caught a line you like? Save it to your reviews.'),
      h('div', { class: 'field' }, h('label', { for: 'ml' }, 'Korean'), ta), h('div', { class: 'field' }, h('label', { for: 'mn' }, 'Meaning'), note),
      h('button', { class: 'btn btn-primary', onclick: () => {
        const ko = ta.value.trim(); if (!ko) return toast('Type the Korean line first');
        const mid = Date.now().toString(36);
        st.mylines.push({ id: mid, ko, en: note.value.trim(), clip: c.id });
        st.cards['M:' + mid] = grade({ k: 'M:' + mid, u: 0, l: '' }, 3, today());
        save(true); ta.value = ''; note.value = ''; toast('Added to your reviews');
      } }, 'Save line')));
}
